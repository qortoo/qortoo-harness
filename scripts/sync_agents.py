#!/usr/bin/env python3
"""Generate Claude Code and Codex definitions from shared agent definitions in agents/.

Supports:
- Auto-discovery of all role definitions under agents/*.md
- Dual-generation of Claude Code plugin definitions and native Codex TOML definitions
- --check mode for CI drift detection
- Configurable model tiers and plugin targets per agent
"""

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]

# Agent registry defining generator metadata per shared agent role.
# Can also be declared via YAML frontmatter in agents/<name>.md.
AGENT_REGISTRY = {
    "bench-agent": {
        "description": (
            "Develop and maintain qortoo-bench: workloads, measurement correctness, "
            "runners, CI, result analysis, and regression investigation across Rust and Go."
        ),
        "target_plugin": "plugins/qortoo-shared/agents/bench-agent.md",
        "claude_model": "inherit",
        "codex_target": ".codex/agents/bench-agent.toml",
        "codex_model": "gpt-6.1-sol",
        "codex_effort": "high",
    },
}


def parse_frontmatter(text: str) -> tuple[dict, str]:
    """Extract YAML frontmatter and body from markdown if present."""
    if not text.startswith("---\n"):
        return {}, text

    parts = text.split("\n---\n", 1)
    if len(parts) != 2:
        return {}, text

    raw_yaml, body = parts
    frontmatter = {}
    for line in raw_yaml[4:].splitlines():
        if ":" in line:
            key, val = line.split(":", 1)
            key = key.strip()
            val = val.strip().strip('"').strip("'")
            frontmatter[key] = val

    return frontmatter, body.strip() + "\n"


def sync_agent(agent_name: str, check: bool = False) -> list[str]:
    """Sync Claude and Codex definitions for a given agent. Returns list of stale files if in check mode."""
    agent_source = ROOT / "agents" / f"{agent_name}.md"
    if not agent_source.exists():
        raise FileNotFoundError(f"Agent definition not found: {agent_source}")

    raw_text = agent_source.read_text(encoding="utf-8")
    fm, body = parse_frontmatter(raw_text)

    # Resolve metadata: frontmatter overrides registry defaults
    meta = AGENT_REGISTRY.get(agent_name, {})
    description = fm.get("description", meta.get("description", f"Shared agent for {agent_name}"))
    target_plugin = fm.get("target_plugin", meta.get("target_plugin", f"plugins/qortoo-shared/agents/{agent_name}.md"))
    claude_model = fm.get("claude_model", meta.get("claude_model", "inherit"))
    codex_target = fm.get("codex_target", meta.get("codex_target", f".codex/agents/{agent_name}.toml"))
    codex_model = fm.get("codex_model", meta.get("codex_model", "gpt-6.1-sol"))
    codex_effort = fm.get("codex_effort", meta.get("codex_effort", "high"))

    if "'''" in body:
        raise ValueError(f"Agent '{agent_name}' body contains TOML literal string delimiter (''')")

    quoted_description = json.dumps(description)
    outputs = {
        ROOT / target_plugin: (
            f"---\nname: {agent_name}\ndescription: {quoted_description}\nmodel: {claude_model}\n---\n\n"
            f"<!-- Generated by scripts/sync_agents.py; edit agents/{agent_name}.md. -->\n\n"
            + body
        ),
        ROOT / codex_target: (
            "# Generated by scripts/sync_agents.py; edit the shared role or generator.\n"
            f'name = "{agent_name}"\ndescription = {quoted_description}\n'
            f'model = "{codex_model}"\nmodel_reasoning_effort = "{codex_effort}"\n'
            "developer_instructions = '''\n" + body + "'''\n"
        ),
    }

    stale = []
    for path, content in outputs.items():
        relative = path.relative_to(ROOT)
        if check:
            if not path.exists() or path.read_text(encoding="utf-8") != content:
                stale.append(str(relative))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content, encoding="utf-8")
            print(f"Generated {relative}")

    return stale


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Fail if generated files differ")
    parser.add_argument("--agent", type=str, help="Target only a specific agent (e.g. bench-agent)")
    args = parser.parse_args()

    agents_dir = ROOT / "agents"
    if not agents_dir.exists():
        print(f"No agents directory found at {agents_dir}", file=sys.stderr)
        sys.exit(0)

    if args.agent:
        candidate_names = [args.agent]
    else:
        candidate_names = [p.stem for p in sorted(agents_dir.glob("*.md"))]

    total_stale = []
    for name in candidate_names:
        try:
            stale = sync_agent(name, check=args.check)
            total_stale.extend(stale)
        except Exception as e:
            parser.error(str(e))

    if args.check:
        if total_stale:
            parser.exit(1, "Out of date: " + ", ".join(total_stale) + "\n")
        else:
            print("Shared agent definitions are in sync.")


if __name__ == "__main__":
    main()

