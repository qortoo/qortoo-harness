#!/usr/bin/env python3
"""Synchronize shared conventions in this harness and repositories in manifest.toml.

Embeds canonical policy rules inside managed markdown comment blocks:
  <!-- BEGIN QORTOO-HARNESS MANAGED BLOCK -->
  ...
  <!-- END QORTOO-HARNESS MANAGED BLOCK -->

Supports --check mode for CI and diagnostic validation.
"""

from __future__ import annotations

import argparse
from dataclasses import dataclass
import difflib
import sys
from pathlib import Path

from harness_manifest import Manifest, ManifestError, load_manifest, repositories_with_harness

ROOT = Path(__file__).resolve().parents[1]

BEGIN_MARKER = "<!-- BEGIN QORTOO-HARNESS MANAGED BLOCK -->"
END_MARKER = "<!-- END QORTOO-HARNESS MANAGED BLOCK -->"
HEADER_NOTE = "<!-- Generated by qortoo-harness; edit policies/shared-conventions.md in that repository. -->"

SOURCE_RELATIVE_PATH = Path("policies/shared-conventions.md")


def get_managed_block() -> str:
    """Build the deployed block from the single canonical policy file."""
    source_path = ROOT / SOURCE_RELATIVE_PATH
    conventions = source_path.read_text(encoding="utf-8").strip()
    if not conventions or BEGIN_MARKER in conventions or END_MARKER in conventions:
        raise ValueError(f"Expected nonempty policy text without managed markers: {source_path}")
    return f"{BEGIN_MARKER}\n{HEADER_NOTE}\n{conventions}\n{END_MARKER}"


def update_agents_md(existing_content: str, repo_name: str, initialize: bool = False) -> str:
    """Replace one complete block or explicitly enroll an unmarked document."""
    managed_block = get_managed_block()
    begin_count = existing_content.count(BEGIN_MARKER)
    end_count = existing_content.count(END_MARKER)
    if not begin_count and not end_count:
        if not initialize:
            raise ValueError(f"{repo_name}: no managed block; review and use --initialize to enroll")
        if not existing_content:
            return scaffold_new_agents_md()
        separator = "\n" if existing_content.endswith("\n") else "\n\n"
        return existing_content + separator + managed_block + "\n"

    lines = existing_content.splitlines()
    if (
        begin_count != 1 or end_count != 1
        or lines.count(BEGIN_MARKER) != 1 or lines.count(END_MARKER) != 1
        or existing_content.index(BEGIN_MARKER) >= existing_content.index(END_MARKER)
    ):
        raise ValueError(f"{repo_name}: malformed or duplicate managed markers; repair manually")

    start = existing_content.index(BEGIN_MARKER)
    end = existing_content.index(END_MARKER) + len(END_MARKER)
    if existing_content[start + len(BEGIN_MARKER):].startswith("\r\n"):
        managed_block = managed_block.replace("\n", "\r\n")
    return existing_content[:start] + managed_block + existing_content[end:]


def scaffold_new_agents_md() -> str:
    """Create only generic guidance; repository-specific content is owner-authored."""
    return f"# Repository Guidelines\n\n{get_managed_block()}\n"



@dataclass(frozen=True)
class Deployment:
    """One generated text file and its observed preflight content."""

    name: str
    path: Path
    current: str | None
    target: str

    @property
    def stale(self) -> bool:
        return self.current != self.target


def plan_conventions(manifest: Manifest, repo: str | None = None, initialize: bool = False) -> list[Deployment]:
    """Validate the entire requested policy scope without writing any files."""
    get_managed_block()
    repositories = repositories_with_harness(manifest)
    if repo and repo not in repositories:
        raise ValueError(f"Unknown repository: {repo}")
    if repo and repositories[repo].agents_md != 'managed':
        raise ValueError(f"{repo}: AGENTS.md is unmanaged; no policy target selected")
    deployments = []
    errors = []
    for name, entry in sorted(repositories.items()):
        if (repo and name != repo) or entry.agents_md != 'managed':
            continue
        path = entry.path / 'AGENTS.md'
        try:
            if not entry.path.is_dir():
                raise ValueError(f"{name}: repository directory is missing")
            if path.is_symlink():
                raise ValueError(f"{name}: refusing symlink AGENTS.md")
            current = path.read_bytes().decode('utf-8') if path.exists() else None
            target = update_agents_md(current or '', name, initialize)
            deployments.append(Deployment(name, path, current, target))
        except (OSError, ValueError) as error:
            errors.append(f"{path}: {error}")
    if errors:
        raise ValueError('Cannot synchronize conventions:\n' + '\n'.join(errors))
    return deployments


def finish_deployments(deployments: list[Deployment], *, check: bool = False, diff: bool = False) -> int:
    """Report or apply a fully validated plan, refusing changes since preflight."""
    stale = [item for item in deployments if item.stale]
    if not check and not diff:
        for item in stale:
            current = item.path.read_bytes().decode('utf-8') if item.path.exists() else None
            if item.path.is_symlink() or current != item.current:
                raise ValueError(f'{item.path}: target changed after preflight; rerun synchronization')
        for item in stale:
            item.path.parent.mkdir(parents=True, exist_ok=True)
            item.path.write_bytes(item.target.encode('utf-8'))
            print(f'Updated {item.path}')
    if diff:
        for item in stale:
            print(''.join(difflib.unified_diff(
                (item.current or '').splitlines(keepends=True), item.target.splitlines(keepends=True),
                fromfile=f'a/{item.name}', tofile=f'b/{item.name}',
            )))
    if check and stale:
        print('Out of sync: ' + ', '.join(item.name for item in stale), file=sys.stderr)
        return 1
    if check:
        print(f'In sync: {len(deployments)} generated files checked.')
    return 0

def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check",
        action="store_true",
        help="Check whether all repository AGENTS.md conventions are in sync without writing changes.",
    )
    parser.add_argument(
        "--diff",
        action="store_true",
        help="Show unified diff of changes that would be written without modifying files.",
    )
    parser.add_argument(
        "--repo",
        type=str,
        help="Target qortoo-harness or a specific repository from the manifest.",
    )
    parser.add_argument(
        "--initialize",
        action="store_true",
        help="Enroll missing or unmarked AGENTS.md files without removing existing text.",
    )
    args = parser.parse_args()

    try:
        manifest = load_manifest(ROOT)
    except ManifestError as error:
        parser.exit(1, f"Cannot load manifest: {error}\n")
    try:
        deployments = plan_conventions(manifest, args.repo, args.initialize)
        result = finish_deployments(deployments, check=args.check, diff=args.diff)
    except (OSError, ValueError) as error:
        parser.exit(1, f"Cannot synchronize: {error}\n")
    raise SystemExit(result)


if __name__ == "__main__":
    main()
