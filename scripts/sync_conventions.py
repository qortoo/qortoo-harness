#!/usr/bin/env python3
"""Synchronize shared conventions in this harness and repositories in manifest.toml.

Embeds canonical policy rules inside managed markdown comment blocks:
  <!-- BEGIN QORTOO-HARNESS MANAGED BLOCK -->
  ...
  <!-- END QORTOO-HARNESS MANAGED BLOCK -->

Supports --check mode for CI and diagnostic validation.
"""

import argparse
import difflib
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]

BEGIN_MARKER = "<!-- BEGIN QORTOO-HARNESS MANAGED BLOCK -->"
END_MARKER = "<!-- END QORTOO-HARNESS MANAGED BLOCK -->"
HEADER_NOTE = "<!-- Generated by qortoo-harness; edit policies/shared-conventions.md in that repository. -->"

SOURCE_RELATIVE_PATH = Path("policies/shared-conventions.md")


def get_managed_block() -> str:
    """Build the deployed block from the single canonical policy file."""
    source_path = ROOT / SOURCE_RELATIVE_PATH
    conventions = source_path.read_text(encoding="utf-8").strip()
    if not conventions or BEGIN_MARKER in conventions or END_MARKER in conventions:
        raise ValueError(f"Expected nonempty policy text without managed markers: {source_path}")
    return f"{BEGIN_MARKER}\n{HEADER_NOTE}\n{conventions}\n{END_MARKER}"


def parse_simple_toml(content: str) -> dict:
    """Lightweight, zero-dependency TOML parser for basic sections and string/list values."""
    data = {}
    current_section = data
    section_map = {}

    for line in content.splitlines():
        line = line.strip()
        if not line or line.startswith("#"):
            continue

        # Section header e.g. [workspace] or [repositories.qortoo-rs]
        if line.startswith("[") and line.endswith("]"):
            section_name = line[1:-1].strip()
            parts = section_name.split(".")
            target = data
            for part in parts:
                if part not in target:
                    target[part] = {}
                target = target[part]
            current_section = target
            continue

        # Key-value pair e.g. path = "qortoo-rs" or tools = ["cargo", "rustc"]
        if "=" in line:
            key, val = line.split("=", 1)
            key = key.strip()
            val = val.strip()

            # String
            if val.startswith('"') and val.endswith('"'):
                current_section[key] = val[1:-1]
            # List
            elif val.startswith("[") and val.endswith("]"):
                items = []
                raw_items = val[1:-1].split(",")
                for item in raw_items:
                    item = item.strip()
                    if item.startswith('"') and item.endswith('"'):
                        items.append(item[1:-1])
                current_section[key] = items
            # Boolean
            elif val.lower() == "true":
                current_section[key] = True
            elif val.lower() == "false":
                current_section[key] = False
            else:
                current_section[key] = val

    return data


def load_manifest() -> dict:
    """Load canonical manifest.toml and merge optional local overlay manifest.local.toml."""
    manifest_path = ROOT / "manifest.toml"
    if not manifest_path.exists():
        raise FileNotFoundError(f"Manifest not found: {manifest_path}")

    config = parse_simple_toml(manifest_path.read_text(encoding="utf-8"))

    local_path = ROOT / "manifest.local.toml"
    if local_path.exists():
        local_config = parse_simple_toml(local_path.read_text(encoding="utf-8"))
        # Merge workspace
        if "workspace" in local_config:
            config.setdefault("workspace", {}).update(local_config["workspace"])
        # Merge repositories
        if "repositories" in local_config:
            for repo, props in local_config["repositories"].items():
                if repo in config.get("repositories", {}):
                    config["repositories"][repo].update(props)
                else:
                    config.setdefault("repositories", {})[repo] = props

    return config


def update_agents_md(existing_content: str, repo_name: str, initialize: bool = False) -> str:
    """Replace one complete block or explicitly enroll an unmarked document."""
    managed_block = get_managed_block()
    begin_count = existing_content.count(BEGIN_MARKER)
    end_count = existing_content.count(END_MARKER)
    if not begin_count and not end_count:
        if not initialize:
            raise ValueError(f"{repo_name}: no managed block; review and use --initialize to enroll")
        if not existing_content:
            return scaffold_new_agents_md()
        separator = "\n" if existing_content.endswith("\n") else "\n\n"
        return existing_content + separator + managed_block + "\n"

    lines = existing_content.splitlines()
    if (
        begin_count != 1 or end_count != 1
        or lines.count(BEGIN_MARKER) != 1 or lines.count(END_MARKER) != 1
        or existing_content.index(BEGIN_MARKER) >= existing_content.index(END_MARKER)
    ):
        raise ValueError(f"{repo_name}: malformed or duplicate managed markers; repair manually")

    start = existing_content.index(BEGIN_MARKER)
    end = existing_content.index(END_MARKER) + len(END_MARKER)
    if existing_content[start + len(BEGIN_MARKER):].startswith("\r\n"):
        managed_block = managed_block.replace("\n", "\r\n")
    return existing_content[:start] + managed_block + existing_content[end:]


def scaffold_new_agents_md() -> str:
    """Create only generic guidance; repository-specific content is owner-authored."""
    return f"# Repository Guidelines\n\n{get_managed_block()}\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check",
        action="store_true",
        help="Check whether all repository AGENTS.md conventions are in sync without writing changes.",
    )
    parser.add_argument(
        "--diff",
        action="store_true",
        help="Show unified diff of changes that would be written without modifying files.",
    )
    parser.add_argument(
        "--repo",
        type=str,
        help="Target qortoo-harness or a specific repository from the manifest.",
    )
    parser.add_argument(
        "--initialize",
        action="store_true",
        help="Enroll missing or unmarked AGENTS.md files without removing existing text.",
    )
    args = parser.parse_args()

    # Validate the canonical source before processing any generated files.
    try:
        get_managed_block()
    except (OSError, ValueError) as error:
        parser.exit(1, f"Cannot load shared conventions: {error}\n")

    manifest = load_manifest()
    workspace_root = ROOT / manifest.get("workspace", {}).get("root", "..")
    repositories = dict(manifest.get("repositories", {}))
    # The harness is always a deployment target, independent of workspace overlays.
    repositories["qortoo-harness"] = {"path": str(ROOT), "agents_md": "managed"}
    if args.repo and args.repo not in repositories:
        parser.error(f"Unknown repository: {args.repo}")

    # Preflight every selected file before writing any of them.
    deployments = []
    errors = []
    for repo_name, repo_meta in sorted(repositories.items()):
        if args.repo and repo_name != args.repo:
            continue
        if repo_meta.get("agents_md") != "managed":
            continue
        repo_dir = (workspace_root / repo_meta.get("path", repo_name)).resolve()
        agents_md_path = repo_dir / "AGENTS.md"
        if not repo_dir.exists():
            print(f"Skipping {repo_name}: directory does not exist ({repo_dir})")
            continue
        try:
            if agents_md_path.is_symlink():
                raise ValueError(f"{repo_name}: refusing symlink AGENTS.md")
            current_content = (
                agents_md_path.read_bytes().decode("utf-8") if agents_md_path.exists() else ""
            )
            target_content = update_agents_md(current_content, repo_name, args.initialize)
            deployments.append((repo_name, agents_md_path, current_content, target_content))
        except (OSError, UnicodeError, ValueError) as error:
            errors.append(f"{agents_md_path}: {error}")
    if errors:
        parser.exit(1, "Cannot synchronize conventions:\n" + "\n".join(errors) + "\n")

    stale = []
    for repo_name, agents_md_path, current_content, target_content in deployments:
        if current_content != target_content:
            stale.append(repo_name)
            if args.diff:
                print("".join(difflib.unified_diff(
                    current_content.splitlines(keepends=True),
                    target_content.splitlines(keepends=True),
                    fromfile=f"a/{repo_name}/AGENTS.md",
                    tofile=f"b/{repo_name}/AGENTS.md",
                )))
            elif not args.check:
                agents_md_path.write_bytes(target_content.encode("utf-8"))
                print(f"Updated {agents_md_path}")
        elif not args.check and not args.diff:
            print(f"In sync: {agents_md_path}")

    if args.check:
        if stale:
            parser.exit(1, f"Out of sync: {', '.join(stale)}\n")
        print("All repository AGENTS.md conventions are in sync.")


if __name__ == "__main__":
    main()
